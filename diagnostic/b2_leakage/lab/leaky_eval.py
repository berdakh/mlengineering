from pathlib import Path

import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import average_precision_score, roc_auc_score
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

DATA = Path(__file__).resolve().parents[2] / "data" / "churn_export_full.csv"

df = pd.read_csv(DATA)
y = df["churned_30d"]
X = df.drop(columns=["churned_30d", "customer_id", "snapshot_date"])
X = pd.get_dummies(X, columns=["plan", "country", "acquisition_channel"], dummy_na=True)
X = X.fillna(X.median())
X = pd.DataFrame(StandardScaler().fit_transform(X), columns=X.columns)

X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.3, random_state=0, stratify=y)
model = LogisticRegression(max_iter=2000).fit(X_train, y_train)
p = model.predict_proba(X_test)[:, 1]

if __name__ == "__main__":
    print(f"test prevalence     {y_test.mean():.3f}")
    print(f"average precision   {average_precision_score(y_test, p):.3f}")
    print(f"ROC AUC             {roc_auc_score(y_test, p):.3f}")
    print("-> ready to ship?")
