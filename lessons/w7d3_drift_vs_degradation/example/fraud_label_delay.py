"""Worked example (SYNTHETIC): card-fraud alerts whose labels arrive late and selectively.

    python lessons/w7d3_drift_vs_degradation/example/fraud_label_delay.py

A different domain on purpose. Everything here is generated by the stated rules below; nothing can
be concluded about real fraud rates. Only numpy and pandas are used.

The bank:
* 4,000 transactions a day for 12 weeks; 0.5 % are fraud.
* The model scores each transaction; fraud scores ~ N(2.5, 1), legitimate ~ N(0, 1).
* The top 40 scores of each day become alerts. Analysts review the alerts the same week, so
  alert verdicts arrive 1-3 days later. Nobody reviews the rest.
* Missed fraud surfaces only as a chargeback, 30-90 days after the transaction, for 90 % of it.
* From week 7 a new fraud pattern appears: half of the fraud scores like legitimate traffic
  (N(0, 1)). The score distribution of all transactions barely moves (fraud is 0.5 % of it).
"""
from __future__ import annotations

import numpy as np
import pandas as pd

RNG = np.random.default_rng(42)
DAYS, PER_DAY, FRAUD_RATE, ALERTS_PER_DAY = 84, 4000, 0.005, 40


def simulate() -> pd.DataFrame:
    rows = []
    for d in range(DAYS):
        fraud = RNG.random(PER_DAY) < FRAUD_RATE
        score = RNG.normal(0, 1, PER_DAY)
        new_pattern = (d >= 42) & (RNG.random(PER_DAY) < 0.5)
        score[fraud & ~new_pattern] = RNG.normal(2.5, 1, (fraud & ~new_pattern).sum())
        alert = np.zeros(PER_DAY, bool)
        alert[np.argsort(-score)[:ALERTS_PER_DAY]] = True
        verdict_day = np.where(alert, d + RNG.integers(1, 4, PER_DAY), np.inf)
        chargeback = fraud & ~alert & (RNG.random(PER_DAY) < 0.9)
        chargeback_day = np.where(chargeback, d + RNG.integers(30, 91, PER_DAY), np.inf)
        rows.append(pd.DataFrame({"day": d, "score": score, "fraud": fraud, "alert": alert,
                                  "verdict_day": verdict_day, "chargeback_day": chargeback_day}))
    return pd.concat(rows, ignore_index=True)


def psi(ref: np.ndarray, cur: np.ndarray, bins: int = 10) -> float:
    edges = np.quantile(ref, np.linspace(0, 1, bins + 1))
    edges[0], edges[-1] = -np.inf, np.inf
    r = np.maximum(np.histogram(ref, edges)[0] / len(ref), 1e-4)
    c = np.maximum(np.histogram(cur, edges)[0] / len(cur), 1e-4)
    return float(np.sum((c - r) * np.log(c / r)))


def known_metrics(df: pd.DataFrame, as_of: int) -> dict:
    """What the bank can compute on day ``as_of`` for these transactions."""
    reviewed = df[df["alert"] & (df["verdict_day"] <= as_of)]
    caught = int(reviewed["fraud"].sum())
    missed_known = int((df["chargeback_day"] <= as_of).sum())
    return {"precision": reviewed["fraud"].mean() if len(reviewed) else np.nan,
            "recall_est": caught / (caught + missed_known) if caught + missed_known else np.nan,
            "n_known_fraud": caught + missed_known}


def main() -> None:
    df = simulate()
    df["week"] = df["day"] // 7
    ref = df[df["week"] < 4]["score"].to_numpy()
    rows = []
    for w, g in df.groupby("week"):
        true_recall = g[g["fraud"]]["alert"].mean()
        row = {"week": w + 1, "psi_scores": psi(ref, g["score"].to_numpy()), "true_recall": true_recall}
        for lag in (7, 30, 120):
            m = known_metrics(g, as_of=(w + 1) * 7 + lag)
            row[f"recall_est_+{lag}d"] = m["recall_est"]
            if lag == 7:
                row["precision_+7d"] = m["precision"]
        rows.append(row)
    table = pd.DataFrame(rows)
    pd.set_option("display.width", 120)
    print(table.to_string(index=False, float_format=lambda v: f"{v:.2f}"))
    before, after = table[table["week"] <= 6], table[table["week"] >= 7]
    print(f"\nmean true recall: weeks 1-6 {before['true_recall'].mean():.2f}, weeks 7-12 {after['true_recall'].mean():.2f}")
    print(f"max PSI of the score distribution, weeks 5-12: {table[table['week'] >= 5]['psi_scores'].max():.3f}")
    print(f"mean precision of reviewed alerts (+7 d): weeks 1-6 {before['precision_+7d'].mean():.2f}, "
          f"weeks 7-12 {after['precision_+7d'].mean():.2f}")


if __name__ == "__main__":
    main()
