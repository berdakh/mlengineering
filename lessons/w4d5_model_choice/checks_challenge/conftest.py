"""Fixtures for the w4d5 challenge checks. Grades <target>/analyse.py and <target>/MEMO.md.

All data is SYNTHETIC (generated by challenge/make_case.py, which the checks run themselves).
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import pytest
from sklearn.metrics import roc_auc_score

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
UNIT_DIR = HERE.parent
sys.path.insert(0, str(ROOT))

from tools.wbcheck import resolve_target  # noqa: E402

UNIT = "lessons/w4d5_model_choice"
N_BOOT = 300


@pytest.fixture(scope="session")
def target() -> Path:
    return resolve_target(UNIT, "challenge")


@pytest.fixture(scope="session")
def analyse(target):
    path = target / "analyse.py"
    assert path.is_file(), f"missing {path}"
    spec = importlib.util.spec_from_file_location("learner_analyse", path)
    module = importlib.util.module_from_spec(spec)
    sys.path.insert(0, str(target))
    spec.loader.exec_module(module)
    return module.analyse


def _make(variant: str, out: Path, **overrides) -> Path:
    spec = importlib.util.spec_from_file_location("make_case", UNIT_DIR / "challenge" / "make_case.py")
    mk = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mk)
    mk.write(out, variant)
    if overrides:
        case = json.loads((out / "case.json").read_text())
        case.update(overrides)
        (out / "case.json").write_text(json.dumps(case))
    return out


@pytest.fixture(scope="session")
def cases(tmp_path_factory):
    base = tmp_path_factory.mktemp("cases")
    return {
        "default": _make("default", base / "default"),
        "clear_win": _make("clear_win", base / "clear_win"),
        "default_loose_latency": _make("default", base / "loose", p95_budget_ms=500.0),
        "clear_win_tight_latency": _make("clear_win", base / "tight", p95_budget_ms=5.0),
    }


@pytest.fixture(scope="session")
def results(analyse, cases):
    return {name: analyse(path, n_boot=N_BOOT, seed=0) for name, path in cases.items()}


@pytest.fixture(scope="session")
def reference_widths(cases):
    """Widths of the 95 % interval for B - A by region (cluster) and by customer (row) bootstrap."""
    preds = pd.read_csv(cases["default"] / "predictions.csv")
    y, a, b = (preds[c].to_numpy() for c in ("churned", "score_a", "score_b"))
    groups = [g.index.to_numpy() for _, g in preds.groupby("region")]
    rng = np.random.default_rng(12345)
    cl, rw = [], []
    for _ in range(N_BOOT):
        idx = np.concatenate([groups[k] for k in rng.integers(0, len(groups), len(groups))])
        cl.append(roc_auc_score(y[idx], b[idx]) - roc_auc_score(y[idx], a[idx]))
        idx = rng.integers(0, len(y), len(y))
        rw.append(roc_auc_score(y[idx], b[idx]) - roc_auc_score(y[idx], a[idx]))
    width = lambda d: float(np.subtract(*np.percentile(d, [97.5, 2.5])))  # noqa: E731
    return {"cluster": width(cl), "row": width(rw)}
